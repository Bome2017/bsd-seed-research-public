#!/usr/bin/env python3
"""Generate review/SYNTHESIS_CHECK_BRIEF.md: complete propositions with their full dependency closure (no excerpts),
followed by the contradictions register and the cross-connections, verbatim. Regenerate after any spec change."""
import json, sys
from pathlib import Path

REL = Path(__file__).resolve().parent.parent
claims = json.loads((REL / 'claims' / 'claims.json').read_text())['claims']
by = {c['id']: c for c in claims}


def closure(cid, seen=None):
    seen = set() if seen is None else seen
    for d in by[cid]['depends_on']:
        if d not in seen:
            seen.add(d)
            closure(d, seen)
    return seen


L = ['# Synthesis check brief', '',
     '*Generated by `tools/build_brief.py` from `claims/claims.json`. It contains every proposition in full; nothing is excerpted.*', '',
     '## Purpose', '',
     'You are asked for a final synthesis check of one research record about the elliptic curve',
     '`E: y^2 = x^3 - 22735x^2 + 106272484x` (conductor 6503188012738584). Below are all 76 propositions of the record, each with:',
     '* its kind and evidence grades;',
     '* the published or preprint theorems it imports;',
     '* its direct dependencies, and the full closure of its dependencies;',
     '* its qualifications.', '',
     'The canonical manuscript is `paper/seed_bsd.pdf`, and the evidence is under `evidence/src/`.', '',
     '## Questions', '',
     '1. **Circularity.** Does any proposition graded THEOREM or CONDITIONAL use, directly or through its dependency closure, any of the following as an input:',
     '   * finiteness of Sha(E/Q);',
     '   * #Sha = 9;',
     '   * q = 36;',
     '   * a p-adic BSD formula;',
     '   * a converse of Jones\'s theorem at a multiplicative prime;',
     '   * the equality clause of Stein-Wuthrich Theorem 6.1 at a multiplicative prime?',
     '2. **Direction.** Is any sufficient witness (a nonvanishing coefficient) presented anywhere as necessary, or any failed witness as evidence against a claim?',
     '3. **Labels.** Are the EQUIVALENCE items (S.U, B.9, B.10) and EQUIVALENT_REFORMULATION stops (X.9, X.12) correctly distinguished from reductions? Is every OBSTRUCTION used only within its stated scope?',
     '4. **Shared dependencies.** Consider `CROSS_CONNECTIONS.md` §1: Skinner\'s theorem, Kato, the coefficient verifier, the lattice, and the separate global saturation certificate. Are these the right single points of failure, and are any missing?',
     '5. **The 2243 chain (B.6).** With D2 discharged and D5 certified, is the implication "K nonzero mod 2243 implies Sha[2243^infinity] = 0" complete as stated? Which of D1-D8 carries the most risk?',
     '6. **The two ordinary-bridge proofs (B.3 and the A3 route).** Is the claim that the A3 argument runs at ordinary p correct? If so, which proof should be canonical?',
     '7. **Unresolved contradictions K.1-K.6.** For each, is the recorded status right, and does any of them affect a THEOREM?',
     '8. **Anything missed.** Does one result supply another argument\'s hypothesis in a way the record does not state? Are two apparently separate gaps the same gap?', '',
     'Please answer each question with the proposition ids involved, and keep what you verified separate from what you believe.', '',
     '## All propositions', '']
for c in claims:
    cl = sorted(closure(c['id']))
    L += [f"### {c['id']} — {c['title']}", '', c['statement'], '',
          f"* kind: {c['kind']}" + (f" (stop: {c['stop_kind']})" if c['stop_kind'] else ''),
          f"* grades: {', '.join(c['grades']) or 'none'}",
          f"* direct dependencies: {', '.join(c['depends_on']) or 'none'}",
          f"* full dependency closure: {', '.join(cl) or 'none'}"]
    if c['imports']:
        L.append('* imports: ' + '; '.join(c['imports']))
    if c['scope']:
        L.append('* scope: ' + c['scope'])
    if c['role']:
        L.append('* role: ' + c['role'])
    if c['normalization']:
        L.append('* normalization: ' + c['normalization'])
    for key, value in c['verification'].items():
        L.append('* verification ' + key + ': ' + str(value))
    L.append('* evidence (paths relative to repository root):')
    for ev in c['evidence']:
        L.append('  * `' + ev['path'] + '` — ' + ev['role'] + '; SHA256 `' + ev['sha256'] + '`')
    for q in c['qualifications']:
        L.append('* qualification: ' + q)
    L.append('')
L += ['## Contradictions register (verbatim)', '', (REL / 'claims' / 'CONTRADICTIONS.md').read_text(), '',
      '## Cross-connections (verbatim)', '', (REL / 'claims' / 'CROSS_CONNECTIONS.md').read_text()]
content = '\n'.join(L) + '\n'
path = REL / 'review' / 'SYNTHESIS_CHECK_BRIEF.md'
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != content:
        raise SystemExit('Generated synthesis brief is stale')
else:
    path.write_text(content)
print('brief written:', len(claims), 'propositions')
