#!/usr/bin/env python3
"""Generate coverage/COVERAGE.md: what this release examined, what it includes, and what it does not.

Inputs: the master's SOURCE_BINDINGS.json and RECONCILIATION_INVENTORY.json (read-only), the saved output of the
master's own freshness checker, evidence/PROVENANCE.tsv, evidence/EXCLUDED.tsv, claims/claims.json and
coverage/BUILDER_READING_LOG.json."""
import collections, json
from pathlib import Path

REL = Path(__file__).resolve().parent.parent
MASTER = REL / 'evidence/src/BSD_CODEX6_MASTER_HANDOFF_2026-09-19'
bind = json.loads((MASTER / 'SOURCE_BINDINGS.json').read_text())
inv = json.loads((MASTER / 'RECONCILIATION_INVENTORY.json').read_text())
fresh = sorted((REL / 'coverage').glob('master_freshness_*.json'))[-1]
fr = json.loads(fresh.read_text())
log = json.loads((REL / 'coverage' / 'BUILDER_READING_LOG.json').read_text())
claims = json.loads((REL / 'claims' / 'claims.json').read_text())['claims']

prov = [l.split('\t') for l in (REL / 'evidence' / 'PROVENANCE.tsv').read_text().splitlines()[1:]]
excl = [l.split('\t') for l in (REL / 'evidence' / 'EXCLUDED.tsv').read_text().splitlines()[1:]]
cited = {ev['path'] for c in claims for ev in c['evidence']}
read = set(log['read']['full']) | set(log['read']['partial'])
depth = collections.Counter(s.get('reading_depth', 'unrecorded') for s in bind['sources'])
cat = collections.Counter(r[4] for r in prov)
why = collections.Counter(r[2] for r in excl)
changed = [r[1] for r in prov if r[6] == 'CHANGED_SINCE_MASTER_BINDING']
new_by_folder = collections.Counter()
for iss in fr['issues']:
    if iss['kind'] == 'discovery_scope_changed':
        for p in iss['new_records']:
            new_by_folder[p.split('/')[3]] += 1

L = ['# Coverage: what this release examined and what it did not', '',
     f'*Generated by `tools/build_coverage.py`. Master freshness output: `{fresh.relative_to(REL)}`.*', '',
     '**This release does not claim to contain every BSD record on the originating computer.** It is a derived export. '
     'It contains the canonical master record, every source that record binds, the records created or changed after the '
     'master\'s last integration, and a small set of named extra records. It does not supersede the master record, and it '
     'is not a competing map: later records supersede additively, and differences are listed below without authorizing changes to the frozen master.', '',
     '## 1. The canonical record and its freshness', '',
     f"* Canonical account: `evidence/src/BSD_CODEX6_MASTER_HANDOFF_2026-09-19/MASTER_BSD_DAG.md` (master last integrated 2026-09-21).",
     f"* The master's own checker (`verify_master.py`), run read-only while building: **{fr['result']}**. It checked {fr['bound_sources_checked']} bound sources and {fr['discovered_records']} discovered records.",
     '* Changed bound sources (annotation-only supersession notes added after binding; see `claims/CONTRADICTIONS.md`, K.3):']
L += [f'  * `{p}`' for p in changed]
L += ['* New records discovered since the master\'s last integration, by folder. All are included in this release except the private outreach folder; the builder read them only at the depths recorded in section 3:', '']
L += ['| folder | new records |', '|---|---|'] + [f'| `{f}` | {n} |' for f, n in sorted(new_by_folder.items())]
L += ['', 'The master record itself was **not** modified: it is read-only for this builder, and its reconciliation needs the user\'s authorization.',
      '', '## 2. What the master examined (as it records it)', '',
      f"* Bound sources: {len(bind['sources'])}. Their recorded reading depths:"]
L += [f'  * {n} — {d}' for d, n in depth.most_common()]
L += [f"* Discovery universe at the master's last snapshot: {inv['discovered_record_count']} text records under {len(inv['roots'])} roots.",
      f"  * The master's own words: \"{inv['review_scope']}\"",
      '* Not exhaustively recovered, per the master record (section 7 and `00_READ_FIRST.md`): older Codex and ChatGPT task histories, the ChatGPT Library, the live corrected Drive checkpoint of the H9 history, the research labels H1-H4, compressed archives, personal Documents, and cloud-only material.',
      '', '## 3. What this builder read', '']
L += [f"* In full: {len(log['read']['full'])} records. In part (statement, verdict and status sections): {len(log['read']['partial'])} records. Authored in this session: {', '.join('`' + a + '`' for a in log['read']['authored'])}.",
      '* The list is in `coverage/BUILDER_READING_LOG.json`.',
      f"* Claims whose evidence includes at least one record read by the builder: {sum(1 for c in claims if any(ev['path'].replace('evidence/src/', '') in read for ev in c['evidence']))} of {len(claims)}.",
      '* Every other evidence file was copied, hashed and bound to its claims, but not read by this builder. Auditors should read the cited evidence rather than rely on the builder\'s summaries.',
      '', '## 4. What the release includes', '',
      f"* {len(prov)} files under `evidence/src/`, {sum(int(r[3]) for r in prov) / 1e6:.1f} MB, each with its original path and sha256 (`evidence/PROVENANCE.tsv`). By category:"]
L += [f'  * {n} — {c}' for c, n in cat.most_common()]
L += [f"* {len(cited)} distinct files are cited by the {len(claims)} claims.",
      '* Six text files carry a masked private e-mail thread identifier (`evidence/REDACTIONS.tsv`, which records both hashes).',
      '', '## 5. What the release excludes, and why', '']
L += ['| reason | files |', '|---|---|'] + [f'| {w} | {n} |' for w, n in why.most_common()]
L += ['', 'Third-party publications are cited, not redistributed; their local sha256 values are in `evidence/EXCLUDED.tsv`. The coefficient corpora and run work units are described in `data/LARGE_DATA.md`. Correspondence with named researchers is not included.',
      '', '## 6. Consequence for reviewers', '',
      '* A claim\'s status here is the status in its cited records, integrated with the post-master records listed above. It is not an independent re-audit of every imported theorem, large certificate or Lean build.',
      '* Reruns performed while building this release are listed in `tools/verify_release.py` and `review/VERIFICATION_RUN.md`.',
      '* First-review supplement: `review/FIRST_REVIEW.md` and `review/REVIEW_COVERAGE.md` record 116 restored files, new replays and their limits. The builder reading counts above were not inflated by this later work.']
(REL / 'coverage' / 'COVERAGE.md').write_text('\n'.join(L) + '\n')
print('coverage written;', len(prov), 'included;', len(excl), 'excluded;', len(changed), 'changed bound sources')
