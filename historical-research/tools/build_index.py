#!/usr/bin/env python3
"""Generate claims/claims.json, claims/CLAIM_INDEX.md and claims/LABELS.md from claims/spec (never edit the outputs).

Checks: unique ids; every depends_on id exists; every evidence path exists under evidence/src and is listed in
evidence/PROVENANCE.tsv (its released sha256 is recorded next to it)."""
import json, sys
from pathlib import Path

REL = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REL))
sys.dont_write_bytecode = True
from claims.spec import CLAIMS, GRADES, KINDS, STOP_KINDS, REVIEWS  # noqa: E402

prov = {}
for line in (REL / 'evidence' / 'PROVENANCE.tsv').read_text().splitlines()[1:]:
    f = line.split('\t')
    prov[f[0]] = {'sha256': f[2], 'original_path': f[1], 'binding_check': f[6]}

errors = []
def emit(path, content):
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit('Generated file is stale: ' + str(path.relative_to(REL)))
    else:
        path.write_text(content)

ids = [c['id'] for c in CLAIMS]
dup = {i for i in ids if ids.count(i) > 1}
if dup:
    errors.append(f'duplicate ids: {sorted(dup)}')
known = set(ids)
for c in CLAIMS:
    for d in c['depends_on']:
        if d not in known:
            errors.append(f"{c['id']}: unknown dependency {d}")
    for ev in c['evidence']:
        p = ev['path']
        if not (REL / p).is_file():
            errors.append(f"{c['id']}: missing evidence {p}")
        elif p not in prov:
            errors.append(f"{c['id']}: evidence not in PROVENANCE.tsv {p}")
        else:
            ev['sha256'] = prov[p]['sha256']
            ev['original_path'] = prov[p]['original_path']
# A resolved identifier alone does not exclude a dependency cycle.
by_id = {c['id']: c for c in CLAIMS}
visiting, visited = set(), set()
def visit(cid):
    if cid in visiting:
        errors.append('dependency cycle through ' + cid)
        return
    if cid in visited:
        return
    visiting.add(cid)
    for dep in by_id[cid]['depends_on']:
        if dep in by_id:
            visit(dep)
    visiting.remove(cid)
    visited.add(cid)
for cid in ids:
    visit(cid)
if errors:
    print('\n'.join(errors))
    sys.exit(1)

emit(REL / 'claims' / 'claims.json', json.dumps({'generated_from': 'claims/spec', 'claims': CLAIMS}, indent=1, ensure_ascii=False) + '\n')

SECTION = {'2': 'The curve', '3': 'Rank and the analytic side', '4': 'Primary components of Sha', '5': 'The scalar endgame',
           '6': 'Quadratic twists', '7': 'Sufficient criteria at good primes', '8': 'The bad primes',
           '9': 'Equivalences and reductions', '10': 'Stopped routes', '11': 'Open obligations',
           'A': 'Other curves (context only)', 'B': 'Withdrawn or superseded (do not resurrect)'}
out = ['# Claim-to-evidence index', '',
       '*Generated by `tools/build_index.py` from `claims/spec/`. Do not edit this file; edit the spec and regenerate.*', '',
       'Principal manuscript claims use these ids. The index is generated; the manuscript is edited separately and its semantic correspondence still requires review. Labels are defined in [LABELS.md](LABELS.md). '
       'Evidence paths are relative to the repository root. Each file is a byte-identical copy of the original research record, '
       'except the six files listed in `evidence/REDACTIONS.tsv`. The sha256 shown is that of the released copy.', '',
       '| id | statement | kind | grades | review | since master |', '|---|---|---|---|---|---|']
for c in CLAIMS:
    rev = c['verification'].get('review', '')
    out.append(f"| [{c['id']}](#{c['id'].lower().replace('.', '')}) | {c['title']} | {c['kind']}{(' / ' + c['stop_kind']) if c['stop_kind'] else ''} | "
               f"{', '.join(c['grades']) or '-'} | {rev.split(' ')[0] if rev else '-'} | {'yes' if c['post_master'] else ''} |")
cur = None
for c in CLAIMS:
    if c['section'] != cur:
        cur = c['section']
        out += ['', f"## {SECTION.get(cur, cur)}"]
    out += ['', f"### {c['id']}", '', f"**{c['title']}.** {c['statement']}", '',
            f"* **Kind:** {c['kind']}" + (f" — stop: {c['stop_kind']}" if c['stop_kind'] else ''),
            f"* **Grades:** {', '.join(c['grades']) or 'none (open)'}", f"* **Origin:** {c['origin']}"]
    if c['role']:
        out.append(f"* **Role:** {c['role']}")
    if c['scope']:
        out.append(f"* **Scope:** {c['scope']}")
    if c['normalization']:
        out.append(f"* **Normalization:** {c['normalization']}")
    if c['imports']:
        out.append('* **Imports:** ' + '; '.join(c['imports']))
    if c['depends_on']:
        out.append('* **Depends on:** ' + ', '.join(c['depends_on']))
    for k, v in c['verification'].items():
        out.append(f"* **{k.replace('_', ' ').capitalize()}:** {v}")
    for q in c['qualifications']:
        out.append(f"* **Qualification:** {q}")
    if c['master_ref']:
        out.append(f"* **Master record:** {c['master_ref']}")
    if c['post_master']:
        out.append(f"* **Since the master record:** {c['post_master']}")
    out.append('* **Evidence:**')
    for ev in c['evidence']:
        out.append(f"  * `{ev['path']}` — {ev['role']} (sha256 `{ev['sha256'][:16]}…`)")
emit(REL / 'claims' / 'CLAIM_INDEX.md', '\n'.join(out) + '\n')

lab = ['# Labels used in the claim index', '', '*Generated from `claims/spec/common.py`.*', '', '## Evidence grades', '']
lab += [f'* **{k}** — {v}' for k, v in GRADES.items()]
lab += ['', '## Kinds of statement', ''] + [f'* **{k}** — {v}' for k, v in KINDS.items()]
lab += ['', '## Kinds of stop (never conflated)', ''] + [f'* **{k}** — {v}' for k, v in STOP_KINDS.items()]
lab += ['', '## Review levels', ''] + [f'* **{k}** — {v}' for k, v in REVIEWS.items()]
lab += ['', 'A sufficient witness (for example a nonzero coefficient) is never an obligation: its failure proves nothing, and '
        'the obligation it serves may be met another way.']
emit(REL / 'claims' / 'LABELS.md', '\n'.join(lab) + '\n')
kinds = {}
for c in CLAIMS:
    kinds[c['kind']] = kinds.get(c['kind'], 0) + 1
print(f'{len(CLAIMS)} claims OK; kinds {kinds}; evidence items {sum(len(c["evidence"]) for c in CLAIMS)}')
