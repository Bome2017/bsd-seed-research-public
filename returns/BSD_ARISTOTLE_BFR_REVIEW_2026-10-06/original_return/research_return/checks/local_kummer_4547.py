"""Exact local check at the additive prime p=4547 for the seed minimal model.
Producer = this script (pure Python integers, no floating point, no external library).
Decides whether P1 (resp. P2) generates E(Q_p)/pE(Q_p), via the criterion
   P in E_0 \\ E_1  and  v_p( x((p-1)P) - x(P) ) == 1
(equivalently v_p(t(pP)) = 1, i.e. E_0(Q_p) is torsion-free procyclic generated by P).
Arithmetic modulo p^N with N=8; every division is by an element whose valuation is
checked to be 0 before inversion."""
import json, sys
a1,a2,a3,a4,a6 = 0,-1,0,-66020924,-65074271436
p = 4547; N = 8; M = p**N
F = lambda x: x**3 + a2*x*x + a4*x + a6
def v(n):
    n %= M
    if n == 0: return N
    k = 0
    while n % p == 0: n//=p; k+=1
    return k
def inv(u):
    assert v(u) == 0, "non-unit denominator"
    return pow(u % M, -1, M)
def add(P, Q):
    (x1,y1),(x2,y2) = P,Q
    if (x1-x2) % p == 0:
        assert (x1-x2) % M == 0 and (y1-y2) % M == 0, "unexpected near-collision"
        lam = (3*x1*x1 + 2*a2*x1 + a4) * inv(2*y1) % M
    else:
        lam = (y2-y1)*inv(x2-x1) % M
    x3 = (lam*lam - a2 - x1 - x2) % M
    y3 = (-(y1 + lam*(x3-x1))) % M
    return (x3,y3)
out = {"p": p, "precision_N": N,
       "v_p(Delta)": None, "v_p(c4)": None}
D = 16586638656786071143743744; c4 = 3169004368
def vint(n):
    k=0
    while n % p == 0: n//=p; k+=1
    return k
out["v_p(Delta)"] = vint(D); out["v_p(c4)"] = vint(c4)
# singular point of reduction mod p: solve 2y=0, F'(x)=0, F(x)=0 mod p
sing = [x for x in range(p) if F(x) % p == 0 and (3*x*x+2*a2*x+a4) % p == 0]
out["singular_x_mod_p"] = sing
for name,P in [("P1",(-3031,327384)),("P2",(-2394,281520))]:
    x,y = P
    assert (y*y - F(x)) == 0
    nonsing = not ((2*y) % p == 0 and (3*x*x+2*a2*x+a4) % p == 0)
    rec = {"point": P, "reduction_nonsingular": nonsing, "x_mod_p": x % p, "y_mod_p": y % p}
    if not nonsing:
        rec["in_E0"] = False
        rec["generates_E(Qp)/p"] = "not tested directly: reduction is the singular point, so P lies off the identity component E_0 (component group Z/2)"
        out[name] = rec
        continue
    Pm = (x % M, y % M)
    Q = Pm
    for k in range(2, p):        # Q = kP for k = 2..p-1
        Q = add(Q, Pm)
    rec["in_E0"] = True
    rec["v_p(x((p-1)P)-x(P))"] = v(Q[0]-x)
    rec["v_p(y((p-1)P)+y(P))"] = v(Q[1]+y)
    rec["generates_E(Qp)/p"] = nonsing and (y % p != 0) and rec["v_p(x((p-1)P)-x(P))"] == 1
    out[name] = rec
print(json.dumps(out, indent=1))
