#!/usr/bin/env python3
"""Read-only custody verification and small exact arithmetic replay.

No BNF, source search, GP build, class computation, or remote job is started.
This checker does not turn the saved computations into a complete source bound.
"""
from pathlib import Path
import gzip, hashlib, json, shutil, subprocess, sys, tempfile

ROOT = Path(__file__).resolve().parent

def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()

def check_manifest(m):
    n = 0
    for line in m.read_text().splitlines():
        expected, name = line.split('  ', 1)
        path = (m.parent / name).resolve()
        assert path.is_relative_to(m.parent.resolve()), name
        assert path.is_file() and digest(path) == expected, str(path)
        n += 1
    return n

nested = {}
for m in sorted(ROOT.rglob('MANIFEST.sha256')):
    if m.parent != ROOT:
        nested[str(m.relative_to(ROOT))] = check_manifest(m)

replays = {}
with tempfile.TemporaryDirectory(prefix='bsd-rank-two-return-check-') as temp:
    td = Path(temp)
    for folder, script, inputs, output, marker in [
        ('twist_selection', 'check_model.py', [], 'EXACT_MODEL_CHECK.json',
         'TWIST_MODEL_AND_POINT_CHECK_PASS'),
        ('divisor_control', 'check_local_divisors.py', ['ACTUAL_DIVISORS.json'],
         'LOCAL_DIVISOR_CHECK.json', 'ACTUAL_P7_P5_P131_BINDING_PASS'),
    ]:
        d = td / folder
        d.mkdir()
        for name in [script] + inputs:
            shutil.copyfile(ROOT / folder / name, d / name)
        r = subprocess.run([sys.executable, str(d / script)], cwd=d,
                           capture_output=True, text=True, timeout=15, check=True)
        assert marker in r.stdout
        assert (d / output).read_bytes() == (ROOT / folder / output).read_bytes()
        replays[folder] = {'status': 'PASS', 'saved_output_reproduced_byte_for_byte': True}

# Exact complete valuation-space consequence of the saved actual twist data.
places = json.loads((ROOT / 'twist_divisor/ACTUAL_DIVISORS.json').read_text())
assert [row[0] for row in places] == [7, 11, 47]
for q, ef, perm, chi, inverse_chi in places:
    assert sum(e*f for e, f in ef) == 48
    assert sorted(perm) == list(range(1, len(perm)+1))
    assert all(perm[perm[perm[i]-1]-1] == i+1 for i in range(len(perm)))
    assert pow(3, 3, 7) == pow(5, 3, 7) == 6
    assert chi == inverse_chi == []
replays['twist_divisor'] = {
    'status':'PASS', 'places':[7,11,47],
    'scalar_permutation_cubes_identity':True,
    'faithful_character_cubes_minus_one':True,
    'complete_valuation_allowance':0,
    'actual_field_factorization':'saved arithmetic input, not regenerated by this checker'
}

compression = []
source = ROOT / 'pari_partial_source'
for item in json.loads((source / 'CAPTURE_COMPRESSION.json').read_text()):
    gz = source / item['gzip_name']
    assert gz.stat().st_size == item['gzip_bytes'] and digest(gz) == item['gzip_sha256']
    h = hashlib.sha256()
    size = 0
    with gzip.open(gz, 'rb') as f:
        for block in iter(lambda:f.read(1 << 20), b''):
            size += len(block)
            h.update(block)
    assert size == item['raw_bytes'] and h.hexdigest() == item['raw_sha256']
    compression.append({'gzip':item['gzip_name'],'raw_bytes_verified':size,
                        'raw_and_compressed_hashes':'PASS'})

state = json.loads((ROOT / 'STATE.json').read_text())
assert state['complete_norm_local_rank_profiles'] == 'not measured'
assert state['complete_class_bound'] is None
assert not state['new_rank_two_joint_bound'] and not state['new_seed_prime_result']
assert not state['arithmetic_searches_running']
partial = json.loads((source / 'STATE.json').read_text())
assert partial['first_capture_generators'] == partial['first_capture_central_fixed'] == 1424
assert partial['mixed_filter_logged_trials'] == 92544
assert partial['mixed_accepted_generators'] == partial['admitted_faithful_units'] == 0
assert partial['class_group_bound'] is None and partial['joint_bound'] is None

result = {
    'status':'PASS',
    'scope':'custody plus small exact replays; no full BNF, field, source-search, rank-descent or antecedent-theorem replay',
    'nested_manifest_entries':nested,
    'total_nested_manifest_entries':sum(nested.values()),
    'small_exact_replays':replays,
    'compressed_capture_custody':compression,
    'final_status_consistency':'PASS',
    'new_complete_source_bound':False,
    'FIN_ORDER9_Q36':'unchanged'
}
print(json.dumps(result, indent=2))
